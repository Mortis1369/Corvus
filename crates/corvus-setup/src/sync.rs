//! Copying the payload onto the drive.
//!
//! Two phases: [`plan`] walks the payload and decides which files are new or changed, then
//! [`run`] copies them. Splitting it means the total size is known before the first byte moves
//! (for the progress bar and the free-space check).
//!
//! Rules:
//! * Only new or changed files are copied (size differs, or modified time differs by > 2 s —
//!   exFAT/FAT timestamps are coarser than NTFS, so exact comparison would recopy everything).
//! * Nothing on the drive is ever deleted. Whatever Aiden dropped in by hand stays.
//! * `Installers\` is never touched, and neither are the files CorvusSetup generates itself.
//! * One failed file is logged and skipped. It never stops the run. The exception is a drive
//!   that has gone away (unplugged, or dropped off the USB bus): then the run stops at once.

use std::fs::{self, File};
use std::io::{self, Read, Write};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::{Duration, SystemTime};

const TOLERANCE: Duration = Duration::from_secs(2);
const CHUNK: usize = 4 << 20;
/// Suffix for a file while it is being written; renamed into place when complete.
const PART: &str = ".corvus-part";

/// One file that needs copying. `rel` is relative to the payload root.
#[derive(Debug, Clone, PartialEq)]
pub struct Item {
    pub rel: PathBuf,
    pub size: u64,
}

#[derive(Debug, Default)]
pub struct Plan {
    pub items: Vec<Item>,
    /// Total bytes in `items`.
    pub bytes: u64,
    /// Files already identical on the drive.
    pub unchanged: usize,
    /// Folders or files that could not be read while planning.
    pub problems: Vec<String>,
}

#[derive(Debug, Default)]
pub struct Outcome {
    pub copied: usize,
    pub bytes: u64,
    pub failed: Vec<(PathBuf, String)>,
    pub cancelled: bool,
    /// Set when the copy was abandoned because a drive went away; the text says which.
    pub lost: Option<String>,
}

/// This many failures in a row means something is wrong with a drive, not with a file.
const MAX_FAILURES_IN_A_ROW: usize = 25;

/// After a failed copy: is one of the two drives gone? One bad file is skipped, but when the
/// whole drive has dropped off the USB bus every remaining file would fail the same way, so the
/// run stops instead of logging thousands of identical errors.
fn lost_drive(src: &Path, dst: &Path, failures_in_a_row: usize) -> Option<String> {
    if !dst.exists() {
        return Some(format!("the target drive ({}) disconnected", dst.display()));
    }
    if !src.exists() {
        return Some(format!(
            "the payload folder ({}) became unreachable",
            src.display()
        ));
    }
    (failures_in_a_row >= MAX_FAILURES_IN_A_ROW).then(|| {
        format!("{failures_in_a_row} files in a row failed; a drive is probably disconnecting")
    })
}

/// Paths (relative to the payload root) that the sync must leave alone.
pub fn is_excluded(rel: &Path) -> bool {
    let s = rel
        .to_string_lossy()
        .replace('\\', "/")
        .to_ascii_lowercase();
    s == "staging-report.md"
        || s == "installers"
        || s.starts_with("installers/")
        // generated by CorvusSetup after the copy; a stale copy in the payload must not win
        || s == "ventoy/ventoy.json"
        || s == "ventoy/ventoy-log.md"
        || s == "autorun.inf"
        || s == "launcher/setup-log.txt"
        || s == "launcher/corvus.log"
        || s.ends_with(PART)
}

/// Total size of everything the payload would put on an empty drive.
pub fn payload_size(src: &Path) -> u64 {
    // Planning against a folder that does not exist marks every file as "to copy".
    plan(src, &src.join(".corvus-no-such-drive")).bytes
}

/// Room a Fresh install needs beyond the payload itself: Ventoy's 32 MB boot partition, the
/// file system's own tables, and the rounding-up of every file to a whole cluster.
pub const FRESH_OVERHEAD: u64 = 512 << 20;

/// Decide what needs copying from `src` (payload) to `dst` (drive root).
pub fn plan(src: &Path, dst: &Path) -> Plan {
    let mut p = Plan::default();
    walk(src, Path::new(""), dst, &mut p);
    p.items.sort_by(|a, b| a.rel.cmp(&b.rel));
    p
}

fn walk(src_root: &Path, rel: &Path, dst_root: &Path, p: &mut Plan) {
    let dir = src_root.join(rel);
    let entries = match fs::read_dir(&dir) {
        Ok(e) => e,
        Err(e) => {
            p.problems.push(format!("{}: {e}", dir.display()));
            return;
        }
    };
    for entry in entries.flatten() {
        let rel = rel.join(entry.file_name());
        if is_excluded(&rel) {
            continue;
        }
        let meta = match entry.metadata() {
            Ok(m) => m,
            Err(e) => {
                p.problems.push(format!("{}: {e}", rel.display()));
                continue;
            }
        };
        if meta.is_dir() {
            walk(src_root, &rel, dst_root, p);
        } else if needs_copy(&meta, &dst_root.join(&rel)) {
            p.bytes += meta.len();
            p.items.push(Item {
                rel,
                size: meta.len(),
            });
        } else {
            p.unchanged += 1;
        }
    }
}

fn needs_copy(src: &fs::Metadata, dst: &Path) -> bool {
    let Ok(d) = fs::metadata(dst) else {
        return true; // not there yet
    };
    if d.len() != src.len() {
        return true;
    }
    match (src.modified(), d.modified()) {
        (Ok(a), Ok(b)) => time_gap(a, b) > TOLERANCE,
        _ => false, // same size and no usable timestamps: assume unchanged
    }
}

fn time_gap(a: SystemTime, b: SystemTime) -> Duration {
    a.duration_since(b)
        .or_else(|_| b.duration_since(a))
        .unwrap_or_default()
}

/// Copy one file in chunks, reporting each chunk's size to `on_bytes`. The data goes to a
/// `.corvus-part` file first and is renamed into place, so an interrupted copy never leaves a
/// half-written file under the real name. The modified time is carried over so the next
/// [`plan`] sees the file as unchanged.
pub fn copy_file(
    src: &Path,
    dst: &Path,
    cancel: &AtomicBool,
    on_bytes: &mut dyn FnMut(u64),
) -> io::Result<()> {
    if let Some(parent) = dst.parent() {
        fs::create_dir_all(parent)?;
    }
    let mut part = dst.as_os_str().to_owned();
    part.push(PART);
    let part = PathBuf::from(part);

    let result = (|| {
        let mut input = File::open(src)?;
        let mtime = input.metadata()?.modified().ok();
        let mut output = File::create(&part)?;
        let mut buf = vec![0u8; CHUNK];
        loop {
            if cancel.load(Ordering::Relaxed) {
                return Err(io::Error::new(io::ErrorKind::Interrupted, "cancelled"));
            }
            let n = input.read(&mut buf)?;
            if n == 0 {
                break;
            }
            output.write_all(&buf[..n])?;
            on_bytes(n as u64);
        }
        output.flush()?;
        if let Some(t) = mtime {
            let _ = output.set_modified(t);
        }
        drop(output);
        fs::rename(&part, dst)
    })();
    if result.is_err() {
        let _ = fs::remove_file(&part);
    }
    result
}

/// Copy everything in `plan`. `progress(bytes_done, current_file)` is called after every chunk.
pub fn run(
    src: &Path,
    dst: &Path,
    plan: &Plan,
    cancel: &AtomicBool,
    progress: &mut dyn FnMut(u64, &Path),
) -> Outcome {
    let mut out = Outcome::default();
    let mut done = 0u64;
    let mut failures_in_a_row = 0usize;
    for item in &plan.items {
        if cancel.load(Ordering::Relaxed) {
            out.cancelled = true;
            break;
        }
        let before = done;
        let res = copy_file(
            &src.join(&item.rel),
            &dst.join(&item.rel),
            cancel,
            &mut |n| {
                done += n;
                progress(done, &item.rel);
            },
        );
        match res {
            Ok(()) => {
                out.copied += 1;
                out.bytes += item.size;
                failures_in_a_row = 0;
            }
            Err(e) if e.kind() == io::ErrorKind::Interrupted => {
                out.cancelled = true;
                break;
            }
            Err(e) => {
                log::warn!("copy failed, skipped: {}: {e}", item.rel.display());
                out.failed.push((item.rel.clone(), e.to_string()));
                failures_in_a_row += 1;
                if let Some(why) = lost_drive(src, dst, failures_in_a_row) {
                    log::warn!("copy abandoned: {why}");
                    out.lost = Some(why);
                    break;
                }
            }
        }
        // Keep the bar honest when a file failed part-way or was shorter than planned.
        done = before + item.size;
        progress(done, &item.rel);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write(p: &Path, text: &str) {
        fs::create_dir_all(p.parent().unwrap()).unwrap();
        fs::write(p, text).unwrap();
    }

    fn sync(src: &Path, dst: &Path) -> (Plan, Outcome) {
        let plan = plan(src, dst);
        let out = run(src, dst, &plan, &AtomicBool::new(false), &mut |_, _| {});
        (plan, out)
    }

    #[test]
    fn fresh_copy_then_nothing_to_do() {
        let s = tempfile::tempdir().unwrap();
        let d = tempfile::tempdir().unwrap();
        write(&s.path().join("Tools/Disk/7-Zip/7z.exe"), "seven");
        write(&s.path().join("Launcher/tools.toml"), "x");

        let (plan1, out) = sync(s.path(), d.path());
        assert_eq!(plan1.items.len(), 2);
        assert_eq!(out.copied, 2);
        assert!(out.failed.is_empty());
        assert_eq!(
            fs::read_to_string(d.path().join("Tools/Disk/7-Zip/7z.exe")).unwrap(),
            "seven"
        );

        let (plan2, _) = sync(s.path(), d.path());
        assert!(plan2.items.is_empty(), "second run copies nothing");
        assert_eq!(plan2.unchanged, 2);
    }

    #[test]
    fn changed_file_is_recopied_and_extras_survive() {
        let s = tempfile::tempdir().unwrap();
        let d = tempfile::tempdir().unwrap();
        write(&s.path().join("Launcher/tools.toml"), "old");
        sync(s.path(), d.path());

        write(&d.path().join("Boot/Lockpick.wim"), "dropped in by hand");
        write(&d.path().join("Installers/Windows/win11.iso"), "user iso");
        write(&s.path().join("Launcher/tools.toml"), "new and longer");

        let (plan, out) = sync(s.path(), d.path());
        assert_eq!(plan.items.len(), 1);
        assert_eq!(out.copied, 1);
        assert_eq!(
            fs::read_to_string(d.path().join("Launcher/tools.toml")).unwrap(),
            "new and longer"
        );
        assert!(
            d.path().join("Boot/Lockpick.wim").is_file(),
            "never deletes"
        );
        assert!(d.path().join("Installers/Windows/win11.iso").is_file());
    }

    #[test]
    fn exclusions() {
        let s = tempfile::tempdir().unwrap();
        let d = tempfile::tempdir().unwrap();
        write(&s.path().join("STAGING-REPORT.md"), "report");
        write(&s.path().join("Installers/Windows/stray.iso"), "no");
        write(&s.path().join("ventoy/ventoy.json"), "stale");
        write(&s.path().join("ventoy/theme/corvus/theme.txt"), "theme");
        write(&d.path().join("Installers/Windows/mine.iso"), "mine");

        let (plan, _) = sync(s.path(), d.path());
        assert_eq!(plan.items.len(), 1);
        assert!(d.path().join("ventoy/theme/corvus/theme.txt").is_file());
        assert!(!d.path().join("STAGING-REPORT.md").exists());
        assert!(!d.path().join("ventoy/ventoy.json").exists());
        assert!(!d.path().join("Installers/Windows/stray.iso").exists());
        assert_eq!(
            fs::read_to_string(d.path().join("Installers/Windows/mine.iso")).unwrap(),
            "mine"
        );
    }

    #[test]
    fn one_bad_file_does_not_stop_the_rest() {
        let s = tempfile::tempdir().unwrap();
        let d = tempfile::tempdir().unwrap();
        write(&s.path().join("a/blocked.exe"), "1");
        write(&s.path().join("b/fine.exe"), "2");
        // A *folder* already sits where the file should go, so that one copy must fail.
        fs::create_dir_all(d.path().join("a/blocked.exe/in-the-way")).unwrap();

        let (_, out) = sync(s.path(), d.path());
        assert_eq!(out.copied, 1);
        assert_eq!(out.failed.len(), 1);
        assert!(out.failed[0].0.ends_with("blocked.exe"));
        assert!(d.path().join("b/fine.exe").is_file());
        assert!(
            !d.path().join("a/blocked.exe.corvus-part").exists(),
            "no litter"
        );
    }

    #[test]
    fn a_vanished_drive_stops_the_run() {
        let s = tempfile::tempdir().unwrap();
        let d = tempfile::tempdir().unwrap();
        for i in 0..5 {
            write(&s.path().join(format!("f{i}.bin")), "x");
        }
        let p = plan(s.path(), d.path());
        // The target disappears between planning and copying, as a dropped USB drive does.
        // (`\\?\` stops Windows quietly recreating the folder: a plain file sits in its place.)
        let gone = d.path().join("unplugged");
        fs::write(&gone, "not a folder").unwrap();
        let out = run(
            s.path(),
            &gone.join("root"),
            &p,
            &AtomicBool::new(false),
            &mut |_, _| {},
        );
        assert_eq!(out.copied, 0);
        assert_eq!(
            out.failed.len(),
            1,
            "stops at the first failure, not the fifth"
        );
        assert!(out.lost.unwrap().contains("disconnected"));
    }

    #[test]
    fn payload_size_counts_what_would_be_copied() {
        let s = tempfile::tempdir().unwrap();
        write(&s.path().join("Boot/CorvusPE.iso"), "12345");
        write(&s.path().join("Tools/a.exe"), "678");
        write(
            &s.path().join("STAGING-REPORT.md"),
            "never copied, so never counted",
        );
        assert_eq!(payload_size(s.path()), 8);
    }

    #[test]
    fn many_failures_in_a_row_stop_the_run() {
        assert_eq!(lost_drive(Path::new("."), Path::new("."), 24), None);
        assert!(lost_drive(Path::new("."), Path::new("."), 25).is_some());
    }

    #[test]
    fn progress_reaches_total_and_cancel_stops() {
        let s = tempfile::tempdir().unwrap();
        let d = tempfile::tempdir().unwrap();
        write(&s.path().join("one.bin"), "12345");
        write(&s.path().join("two.bin"), "678");
        let p = plan(s.path(), d.path());
        assert_eq!(p.bytes, 8);
        let mut last = 0;
        run(
            s.path(),
            d.path(),
            &p,
            &AtomicBool::new(false),
            &mut |n, _| last = n,
        );
        assert_eq!(last, 8);

        let d2 = tempfile::tempdir().unwrap();
        let p = plan(s.path(), d2.path());
        let out = run(
            s.path(),
            d2.path(),
            &p,
            &AtomicBool::new(true),
            &mut |_, _| {},
        );
        assert!(out.cancelled);
        assert_eq!(out.copied, 0);
    }
}
